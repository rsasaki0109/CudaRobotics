#!/usr/bin/env python3
"""Identity switches of the motion tracker (gpu_ground_segmentation --moving).

  analyze   on the dev drive (seed 0) and the training seeds 101-110 only:
            every switch of a vehicle's track, by kind
              new-after-gap   a new track after scans in which the vehicle was not tracked
              new-no-gap      a new track although the vehicle was tracked the scan before
                              (the association missed it)
              other-track     the vehicle's cluster joined another existing track
  test      a build against stored baseline numbers on fresh drives (seeds
            201-220 by default, unused by any earlier step); writes <out>.md

Criterion (fixed before the test drives ran): fewer identity switches in
total, not more in significantly more drives than fewer (two-sided sign test,
p < 0.05, on the per-drive counts), the hybrid-with-free-space IoU over all
vehicles not lower by more than 0.005, and the velocity error on the moving
vehicles not higher by more than 0.05 m/s.
"""

import argparse
import csv
import io
import json
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from box_fitting_heldout import ROOT, find_binary, sign_test  # noqa: E402

VEH = {"0", "1", "2", "4", "7", "8"}


def collect(binary, seeds, flags=()):
    obs = os.path.join(ROOT, "tmp", "idsw_obs.csv")
    rows = []
    for seed in seeds:
        subprocess.run([binary, "--no-video", "--moving", "--seed", str(seed), "--obs-csv", obs] + list(flags),
                       cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
        with open(obs, newline="") as f:
            rows += [r for r in csv.DictReader(f) if r["box"] in VEH]
    return rows


def switches(rows):
    """Per (seed, box), walk the scans; return the switch events with their kind."""
    events = []
    by = {}
    for r in rows:
        by.setdefault((r["seed"], r["box"]), []).append(r)
    for key, rs in by.items():
        rs.sort(key=lambda r: int(r["scan"]))
        last_id, last_scan = -1, -10
        for r in rs:
            t = int(r["mtrack"])
            if t < 0:
                continue
            s = int(r["scan"])
            if last_id >= 0 and t != last_id:
                new = int(r["mtrack_scans"]) == 1
                kind = "other-track" if not new else ("new-no-gap" if s == last_scan + 1 else "new-after-gap")
                events.append((key[0], key[1], s, kind, s - last_scan))
            last_id, last_scan = t, s
    return events


def metrics(rows):
    iou = sum(float(r["iou_hyb_fs4"]) for r in rows) / max(1, len(rows))
    v = [float(r["verr_motion"]) for r in rows if float(r["speed"]) > 0 and float(r["verr_motion"]) >= 0]
    return iou, sum(v) / max(1, len(v))


def analyze(args):
    rows = collect(find_binary(), [0] + list(range(101, 111)), args.flags.split())
    ev = switches(rows)
    kinds = {}
    for e in ev:
        kinds[e[3]] = kinds.get(e[3], 0) + 1
    iou, verr = metrics(rows)
    print("dev drive and training seeds 101-110: %d switches %s; IoU %.4f, velocity error %.3f m/s"
          % (len(ev), kinds, iou, verr))
    for e in ev[:40]:
        print("  seed %s box %s scan %d: %s (gap %d)" % e)


def test(args):
    a, b = (int(x) for x in args.seeds.split("-"))
    seeds = list(range(a, b + 1))
    rows = collect(find_binary(), seeds, args.flags.split())
    per = {str(s): 0 for s in seeds}
    for e in switches(rows):
        per[e[0]] += 1
    iou, verr = metrics(rows)
    cur = {"per": per, "iou": iou, "verr": verr}
    base_path = os.path.join(ROOT, "tmp", "idsw_base_%s.json" % args.seeds)
    if args.store_baseline:
        json.dump(cur, open(base_path, "w"))
        print("stored baseline: %d switches, IoU %.4f, velocity error %.3f" % (sum(per.values()), iou, verr))
        return
    base = json.load(open(base_path))
    fewer = sum(per[s] < base["per"][s] for s in per)
    more = sum(per[s] > base["per"][s] for s in per)
    p = sign_test(fewer, more)
    total0, total1 = sum(base["per"].values()), sum(per.values())
    ok = total1 < total0 and not (more > fewer and p < 0.05) and iou >= base["iou"] - 0.005 and verr <= base["verr"] + 0.05
    w = io.StringIO()
    w.write("# Identity switches: test on fresh drives\n\nGenerated by `scripts/box_id_switch_eval.py test` on drives "
            "%s (fresh). Baseline: the tracker before the change.\n\n" % args.seeds)
    w.write("| | identity switches | hybrid + free space IoU (all vehicles) | velocity error, moving |\n"
            "|---|---:|---:|---:|\n")
    w.write("| before | %d | %.3f | %.2f m/s |\n| after | %d | %.3f | %.2f m/s |\n"
            % (total0, base["iou"], base["verr"], total1, iou, verr))
    w.write("\nPer drive: fewer / more switches %d / %d (sign test p %.2g).\n\nCriterion: %s.\n"
            % (fewer, more, p, "met" if ok else "**not met**"))
    with open(os.path.join(ROOT, args.out) + ".md", "w", encoding="utf-8", newline="\n") as f:
        f.write(w.getvalue())
    print(w.getvalue())


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    an = sub.add_parser("analyze")
    an.add_argument("--flags", default="")
    t = sub.add_parser("test")
    t.add_argument("--seeds", default="201-220")
    t.add_argument("--flags", default="")
    t.add_argument("--store-baseline", action="store_true")
    t.add_argument("--out", default="docs/results/box_id_switches_2026-10-06")
    args = ap.parse_args()
    analyze(args) if args.cmd == "analyze" else test(args)


if __name__ == "__main__":
    main()

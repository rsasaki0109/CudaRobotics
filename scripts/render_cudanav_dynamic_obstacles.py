#!/usr/bin/env python3
"""Aggregate ``cudarobotics-cudanav sim --scenario crossing`` runs into a report.

Each run directory holds the CLI's ``summary.json``, ``manifest.json``,
and ``trajectory.csv``. Runs are grouped by condition
(the directory name up to ``_seed``), for example::

    runs/map_seed0/ runs/predicted_seed0/ runs/predicted_degraded_seed1/ ...

Writes ``<prefix>.json``, ``<prefix>.md`` and ``<prefix>.png``.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
import statistics
from typing import Any

CONDITIONS = (
    ("map", "Map only (no prediction)"),
    ("tracked_static", "Tracked, zero velocity"),
    ("predicted", "Tracked + CV prediction (oracle)"),
    ("predicted_degraded", "Tracked + CV prediction (2-frame delay, noise)"),
    ("tracked_scan", "Scan tracker (no oracle) + CV prediction"),
)
SUMMARY_FIELDS = (
    "quality_pass",
    "goal_reached",
    "time_to_goal_s",
    "frames",
    "wall_collisions",
    "dynamic_collisions",
    "contact_frames",
    "minimum_dynamic_clearance_m",
    "pedestrian_yield_frames",
    "all_colliding_evaluations",
    "retreating_evaluations",
    "maximum_non_wall_occupied_cells",
    "odometry_drift_percent",
    "frame_ms_p95",
    "mppi_solve_ms_p95",
    "tracking",
)


def load_runs(root: Path) -> dict[str, list[dict[str, Any]]]:
    groups: dict[str, list[dict[str, Any]]] = {}
    for run in sorted(path for path in root.iterdir() if path.is_dir()):
        condition, _, seed = run.name.rpartition("_seed")
        summary = json.loads((run / "summary.json").read_text(encoding="utf-8"))
        if summary.get("scenario") != "cudanav_s_course_crossing":
            raise ValueError(f"{run} is not a crossing run")
        manifest = json.loads((run / "manifest.json").read_text(encoding="utf-8"))
        groups.setdefault(condition, []).append(
            {
                "run": run.name,
                "seed": int(seed),
                "summary": {field: summary.get(field) for field in SUMMARY_FIELDS},
                "dynamic_mode": summary["dynamic_mode"],
                "observation": summary["observation"],
                "source_digest": manifest.get("provenance", {}).get("source_digest"),
                "path": run,
            }
        )
    return groups


def aggregate(runs: list[dict[str, Any]]) -> dict[str, Any]:
    def values(field: str) -> list[float]:
        return [run["summary"][field] for run in runs if run["summary"][field] is not None]

    times = values("time_to_goal_s")
    return {
        "runs": len(runs),
        "goal_reached": sum(bool(run["summary"]["goal_reached"]) for run in runs),
        "quality_pass": sum(bool(run["summary"]["quality_pass"]) for run in runs),
        "dynamic_collisions": sum(values("dynamic_collisions")),
        "wall_collisions": sum(values("wall_collisions")),
        "contact_frames": sum(values("contact_frames")),
        "median_time_to_goal_s": statistics.median(times) if times else None,
        "minimum_dynamic_clearance_m": min(values("minimum_dynamic_clearance_m")),
        "median_yield_frames": statistics.median(values("pedestrian_yield_frames")),
        "median_retreats": statistics.median(values("retreating_evaluations")),
        "maximum_non_wall_occupied_cells": max(values("maximum_non_wall_occupied_cells")),
        "maximum_frame_ms_p95": max(values("frame_ms_p95")),
        "tracking": _tracking_aggregate(runs),
    }


def _tracking_aggregate(runs: list[dict[str, Any]]) -> dict[str, Any] | None:
    tracked = [run["summary"]["tracking"] for run in runs if run["summary"].get("tracking")]
    if not tracked:
        return None
    visible = sum(t["visible_pedestrian_frames"] for t in tracked)
    matched = sum(t["tracked_pedestrian_frames"] for t in tracked)
    frames = sum(run["summary"]["frames"] for run in runs)
    return {
        "recall": matched / visible if visible else None,
        "median_position_rmse_m": statistics.median(
            t["position_rmse_m"] for t in tracked if t["position_rmse_m"] is not None
        ),
        "median_velocity_rmse_mps": statistics.median(
            t["velocity_rmse_mps"] for t in tracked if t["velocity_rmse_mps"] is not None
        ),
        "false_tracks_per_frame": sum(t["false_track_frames"] for t in tracked) / frames,
    }


def write_markdown(path: Path, report: dict[str, Any]) -> None:
    lines = [
        "# CudaNav crossing pedestrians: dynamic-obstacle MPPI",
        "",
        f"Generated by `scripts/render_cudanav_dynamic_obstacles.py` from "
        f"{report['total_runs']} runs of `cudarobotics-cudanav sim --scenario crossing`.",
        "Synthetic S-course, one traversal, two pedestrians crossing the corridors;",
        "the tracker is a simulator oracle except in the scan-tracker condition."
        " See `docs/cudanav_dynamic_obstacles.md`.",
        "",
        "| Condition | Goal | Robot-caused collisions | Median time to goal | "
        "Min clearance | Median pedestrian yields | Median retreats | Max non-wall cells |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for key, label in CONDITIONS:
        if key not in report["conditions"]:
            continue
        row = report["conditions"][key]["aggregate"]
        time_to_goal = (
            "-" if row["median_time_to_goal_s"] is None else f"{row['median_time_to_goal_s']:.1f} s"
        )
        lines.append(
            f"| {label} | {row['goal_reached']}/{row['runs']} | "
            f"{row['dynamic_collisions'] + row['wall_collisions']} | {time_to_goal} | "
            f"{row['minimum_dynamic_clearance_m']:.2f} m | {row['median_yield_frames']:.0f} | "
            f"{row['median_retreats']:.0f} | {row['maximum_non_wall_occupied_cells']} |"
        )
    tracking_rows = [
        (label, report["conditions"][key]["aggregate"]["tracking"])
        for key, label in CONDITIONS
        if key in report["conditions"] and report["conditions"][key]["aggregate"]["tracking"]
    ]
    if tracking_rows:
        lines += [
            "",
            "Tracking accuracy against the true pedestrians (visible = hit by at least 3 rays;"
            " tracked = a confirmed track within 0.5 m; false = a confirmed track more than"
            " 0.7 m from every pedestrian):",
            "",
            "| Condition | Recall | Median position RMSE | Median velocity RMSE | False tracks per frame |",
            "|---|---|---|---|---|",
        ]
        for label, t in tracking_rows:
            lines.append(
                f"| {label} | {100 * t['recall']:.1f}% | {t['median_position_rmse_m']:.2f} m | "
                f"{t['median_velocity_rmse_mps']:.2f} m/s | {t['false_tracks_per_frame']:.2f} |"
            )
    lines += [
        "",
        "- Goal: runs that reached the goal within 60 s (600 frames).",
        "- Robot-caused collisions: wall contacts plus moves that deepen a pedestrian contact.",
        "- Pedestrian yields: pedestrian-frames spent paused because the robot was in the way.",
        "- Non-wall cells: occupied cells more than 0.15 m from every wall"
        " (leftover traces plus pedestrians currently in the map).",
        "",
        "Per-run results:",
        "",
        "| Run | Goal | Time | Collisions | Min clearance | Yields | Retreats | Frame p95 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for key, _label in CONDITIONS:
        for run in report["conditions"].get(key, {}).get("runs", []):
            s = run["summary"]
            time_to_goal = "-" if s["time_to_goal_s"] is None else f"{s['time_to_goal_s']:.1f} s"
            lines.append(
                f"| {run['run']} | {s['goal_reached']} | {time_to_goal} | "
                f"{s['wall_collisions'] + s['dynamic_collisions']} | "
                f"{s['minimum_dynamic_clearance_m']:.2f} m | {s['pedestrian_yield_frames']} | "
                f"{s['retreating_evaluations']} | {s['frame_ms_p95']:.1f} ms |"
            )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def read_trajectory(run: Path) -> dict[str, list[float]]:
    with (run / "trajectory.csv").open(newline="", encoding="utf-8") as stream:
        rows = list(csv.DictReader(stream))
    return {key: [float(row[key]) for row in rows] for key in rows[0]}


def write_figure(path: Path, groups: dict[str, list[dict[str, Any]]], seed: int) -> bool:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import numpy as np
    except ImportError:
        return False
    shown = [key for key in ("map", "predicted", "tracked_scan") if key in groups]
    figure, axes = plt.subplots(1, len(shown), figsize=(6.5 * len(shown), 4.2))
    axes = np.atleast_1d(axes)
    for axis, key in zip(axes, shown):
        run = next(run for run in groups[key] if run["seed"] == seed)
        trajectory = read_trajectory(run["path"])
        axis.plot(trajectory["truth_x"], trajectory["truth_y"], "b-", lw=1.6, label="robot")
        for obstacle in (0, 1):
            axis.plot(
                trajectory[f"obstacle_{obstacle}_x"], trajectory[f"obstacle_{obstacle}_y"],
                ":", color="tab:orange", lw=1.0, label="pedestrian" if obstacle == 0 else None,
            )
        axis.text(
            0.02, 0.02,
            "max occupied cells off the walls: "
            f"{run['summary']['maximum_non_wall_occupied_cells']}",
            transform=axis.transAxes, fontsize=8,
        )
        label = dict(CONDITIONS)[key]
        result = "goal" if run["summary"]["goal_reached"] else "timeout"
        axis.set_title(f"{label} (seed {seed}: {result})", fontsize=10)
        axis.set_xlim(-1.0, 10.0)
        axis.set_ylim(-2.5, 2.5)
        axis.set_aspect("equal")
        for x0, y0, x1, y1 in (
            (-1.0, -2.5, 10.0, -2.5), (10.0, -2.5, 10.0, 2.5), (10.0, 2.5, -1.0, 2.5),
            (-1.0, 2.5, -1.0, -2.5),
        ):
            axis.plot([x0, x1], [y0, y1], "k-", lw=1.0)
        for min_x, min_y, max_x, max_y in ((3.6, -2.5, 4.3, 0.55), (6.1, -0.55, 6.8, 2.5)):
            axis.add_patch(plt.Rectangle((min_x, min_y), max_x - min_x, max_y - min_y, color="0.6"))
        axis.legend(loc="upper left", fontsize=8)
    figure.tight_layout()
    figure.savefig(path, dpi=110)
    plt.close(figure)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("runs", type=Path, help="directory of crossing run directories")
    parser.add_argument("--output-prefix", type=Path, required=True)
    parser.add_argument("--figure-seed", type=int, default=0)
    args = parser.parse_args()

    groups = load_runs(args.runs)
    digests = {run["source_digest"] for runs in groups.values() for run in runs}
    report = {
        "schema_version": 1,
        "scenario": "cudanav_s_course_crossing",
        "total_runs": sum(len(runs) for runs in groups.values()),
        "source_digests": sorted(digest for digest in digests if digest),
        "claims": {
            "synthetic": True,
            "tracker": "simulator_oracle except tracked_scan (scan tracker)",
            "real_data": False,
        },
        "conditions": {
            key: {
                "dynamic_mode": runs[0]["dynamic_mode"],
                "observation": runs[0]["observation"],
                "aggregate": aggregate(runs),
                "runs": [
                    {k: v for k, v in run.items() if k not in ("path",)} for run in runs
                ],
            }
            for key, runs in groups.items()
        },
    }
    prefix = args.output_prefix
    prefix.parent.mkdir(parents=True, exist_ok=True)
    prefix.with_suffix(".json").write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    write_markdown(prefix.with_suffix(".md"), report)
    if write_figure(prefix.with_suffix(".png"), groups, args.figure_seed):
        print(f"wrote {prefix.with_suffix('.png')}")
    print(f"wrote {prefix.with_suffix('.json')} and {prefix.with_suffix('.md')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Free-space refinement in the trackers (gpu_ground_segmentation --moving).

Variants of the hybrid box (all on the motion tracker, all vehicles of the
--moving drives, boxes with the size prior):

  hybrid    moving tracks: this scan's completed box; parked: the track's box
  hyb_fs1   moving: this scan's refined box; parked: the track's box
  hyb_fs2   moving: this scan's refined box; parked: the track's box refined
            with this scan's free space
  hyb_fs3   as hyb_fs2, on a tracker measured on the refined boxes
  hyb_fs4   moving: this scan's completed box; parked: the refined track box

  select   compares the variants on the dev drive (seed 0) and the training
           seeds 101-110 only, and names the best by mean IoU
  test     one variant against the hybrid on fresh drives (seeds 81-100 by
           default, unused by any earlier step); writes <out>.md

Criterion (fixed before the test drives ran): the variant's mean BEV IoU over
all vehicles is higher than the hybrid's, it is better in significantly more
seeds (two-sided sign test, p < 0.05), its mean centre error is not higher, and
(for hyb_fs3) the velocity error on the moving vehicles rises by at most
0.05 m/s.
"""

import argparse
import csv
import io
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from box_fitting_heldout import ROOT, find_binary, sign_test  # noqa: E402

VEH = {"0", "1", "2", "4", "7", "8"}
VARIANTS = ["hybrid", "hyb_fs1", "hyb_fs2", "hyb_fs3", "hyb_fs4"]


def collect(binary, seeds):
    obs = os.path.join(ROOT, "tmp", "fs_trk_obs.csv")
    rows = []
    for seed in seeds:
        subprocess.run([binary, "--no-video", "--moving", "--seed", str(seed), "--obs-csv", obs], cwd=ROOT,
                       check=True, stdout=subprocess.DEVNULL)
        with open(obs, newline="") as f:
            rows += [r for r in csv.DictReader(f) if r["box"] in VEH]
    return rows


def mean(rows, col):
    return sum(float(r[col]) for r in rows) / max(1, len(rows))


def verr(rows, col):
    v = [float(r[col]) for r in rows if float(r["speed"]) > 0 and float(r[col]) >= 0]
    return sum(v) / max(1, len(v))


def select(args):
    rows = collect(find_binary(), [0] + list(range(101, 111)))
    print("dev drive and training seeds 101-110 (%d vehicle observations)" % len(rows))
    for v in VARIANTS:
        mv = [r for r in rows if float(r["speed"]) > 0]
        pk = [r for r in rows if float(r["speed"]) <= 0]
        print("%-8s IoU all %.4f  moving %.4f  parked %.4f  centre %.3f m" % (v, mean(rows, "iou_" + v), mean(mv, "iou_" + v),
                                                                            mean(pk, "iou_" + v), mean(rows, "centre_" + v)))
    print("velocity error, moving: motion tracker %.3f, measured on refined boxes %.3f m/s"
          % (verr(rows, "verr_motion"), verr(rows, "verr_motion_fs")))


def test(args):
    a, b = (int(x) for x in args.seeds.split("-"))
    rows = collect(find_binary(), range(a, b + 1))
    v = args.variant
    per_seed = {}
    wn = ls = 0
    for r in rows:
        d = float(r["iou_" + v]) - float(r["iou_hybrid"])
        per_seed[r["seed"]] = per_seed.get(r["seed"], 0.0) + d
        wn += d > 1e-9; ls += d < -1e-9
    sw = sum(d > 1e-9 for d in per_seed.values()); sl = sum(d < -1e-9 for d in per_seed.values())
    p = sign_test(sw, sl)
    i0, i1 = mean(rows, "iou_hybrid"), mean(rows, "iou_" + v)
    c0, c1 = mean(rows, "centre_hybrid"), mean(rows, "centre_" + v)
    v0, v1 = verr(rows, "verr_motion"), verr(rows, "verr_motion_fs")
    ok = i1 > i0 and sw > sl and p < 0.05 and c1 <= c0 and (v != "hyb_fs3" or v1 <= v0 + 0.05)
    mv = [r for r in rows if float(r["speed"]) > 0]
    pk = [r for r in rows if float(r["speed"]) <= 0]
    w = io.StringIO()
    w.write("# Free-space refinement in the trackers: test on fresh drives\n\nGenerated by "
            "`scripts/box_fs_tracking_eval.py test --variant %s` (chosen on the dev drive and training seeds 101-110). "
            "Drives %s are fresh. All vehicles of the `--moving` drives, boxes with the size prior.\n\n" % (v, args.seeds))
    w.write("| Box | all: BEV IoU | moving | parked | all: centre error |\n|---|---:|---:|---:|---:|\n")
    for col, name in (("hybrid", "hybrid"), (v, v)):
        w.write("| %s | %.3f | %.3f | %.3f | %.2f m |\n" % (name, mean(rows, "iou_" + col), mean(mv, "iou_" + col),
                                                          mean(pk, "iou_" + col), mean(rows, "centre_" + col)))
    w.write("\n%d observations: better / worse / tie %d / %d / %d (sign test p %.2g); seeds better / worse %d / %d "
            "(p %.2g).\n" % (len(rows), wn, ls, len(rows) - wn - ls, sign_test(wn, ls), sw, sl, p))
    if v == "hyb_fs3":
        w.write("\nVelocity error on the moving vehicles: %.3f -> %.3f m/s.\n" % (v0, v1))
    w.write("\nCriterion: %s.\n" % ("met" if ok else "**not met**"))
    with open(os.path.join(ROOT, args.out) + ".md", "w", encoding="utf-8", newline="\n") as f:
        f.write(w.getvalue())
    print(w.getvalue())


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("select")
    t = sub.add_parser("test")
    t.add_argument("--variant", required=True, choices=VARIANTS[1:])
    t.add_argument("--seeds", default="81-100")
    t.add_argument("--out", default="docs/results/box_fs_tracking_2026-10-06")
    args = ap.parse_args()
    select(args) if args.cmd == "select" else test(args)


if __name__ == "__main__":
    main()

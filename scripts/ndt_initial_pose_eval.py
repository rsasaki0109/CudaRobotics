#!/usr/bin/env python3
"""Initial pose estimation with batched NDT on real LiDAR data: GPU vs CPU.

Runs bin/benchmark_ndt_localization on the MCD ntu_day_02 sequence (exported by
scripts/export_lidar_localization_sequence.py): the map is built from every
10th scan at its ground-truth pose, and 40 test scans lie halfway between map
scans. Each test starts from a GNSS-like position prior (uniform in a disc of
radius r, z within 1 m), roll and pitch from gravity, and unknown yaw.

Configurations (fixed before the run):
  r = 2, 5, 10 m, hypotheses on a 2 m grid covering the disc x 16 yaws
      (144, 576, 1936 hypotheses);
  r = 10 m with a CPU-sized budget: 3 x 3 positions 10 m apart x 8 yaws (72).

Criterion (fixed before the run):
  1. on every CPU-timed scan the CPU and the GPU pick the same hypothesis;
  2. at r = 10 m the full grid succeeds (within 0.5 m and 2 deg) more often
     than the 72-hypothesis budget, paired sign test p < 0.05.
Writes the CSVs and docs/results/ndt_initial_pose_<date>.md.
"""

import argparse
import csv
import io
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from box_fitting_heldout import ROOT, sign_test  # noqa: E402

CONFIGS = [  # name, prior error, grid, grid step, yaws, CPU-timed scans
    ("r2", 2.0, 3, 2.0, 16, 5),
    ("r5", 5.0, 6, 2.0, 16, 3),
    ("r10", 10.0, 11, 2.0, 16, 2),
    ("r10_budget", 10.0, 3, 10.0, 8, 5),
]


def binary():
    for p in ("bin/Release/benchmark_ndt_localization.exe", "bin/benchmark_ndt_localization"):
        if os.path.exists(os.path.join(ROOT, p)):
            return os.path.join(ROOT, p)
    sys.exit("benchmark_ndt_localization not built")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sequence", default="build/datasets/mcd_ntu_day_02/loc_seq_v025.bin")
    ap.add_argument("--date", default="2026-10-07")
    ap.add_argument("--reuse", action="store_true")
    args = ap.parse_args()
    res = {}
    mismatch = 0
    for name, r, grid, step, yaws, cpu in CONFIGS:
        out = os.path.join(ROOT, "docs", "results", "ndt_initial_pose_%s_%s.csv" % (name, args.date))
        log = out[:-4] + ".log"
        if not args.reuse or not os.path.exists(out):
            with open(log, "w") as f:
                subprocess.run([binary(), "--sequence", args.sequence, "--prior-err", str(r), "--grid", str(grid),
                                "--grid-step", str(step), "--yaws", str(yaws), "--cpu-tests", str(cpu), "--csv", out],
                               cwd=ROOT, check=True, stdout=f)
        mismatch += len(re.findall("CPU picks hypothesis", open(log).read()))
        res[name] = list(csv.DictReader(open(out)))
    w = io.StringIO()
    w.write("# Initial pose estimation with batched NDT: GPU vs CPU\n\nGenerated by `scripts/ndt_initial_pose_eval.py` on "
            "MCD ntu_day_02 (40 test scans).\n\n| Prior error | hypotheses | succeeded | tracking from truth < 0.3 m | "
            "GPU ms (mean) | CPU 1 thread ms | CPU 12 threads ms | CPU-timed scans |\n"
            "|---|---:|---:|---:|---:|---:|---:|---:|\n")
    for name, r, grid, step, yaws, cpu in CONFIGS:
        rows = res[name]
        n = len(rows)
        timed = [x for x in rows if float(x["cpu1_ms"]) >= 0]
        mean = lambda v: sum(v) / max(1, len(v))  # noqa: E731
        w.write("| %s m%s | %s | %d/%d | %d/%d | %.0f | %.0f | %.0f | %d |\n" % (
            r, " (budget)" if "budget" in name else "", rows[0]["hypotheses"], sum(int(x["init_ok"]) for x in rows), n,
            sum(float(x["track_err_m"]) < 0.3 for x in rows), n, mean([float(x["gpu_ms"]) for x in rows]),
            mean([float(x["cpu1_ms"]) for x in timed]), mean([float(x["cpun_ms"]) for x in timed]), len(timed)))
    full, bud = res["r10"], res["r10_budget"]
    win = sum(int(a["init_ok"]) > int(b["init_ok"]) for a, b in zip(full, bud))
    loss = sum(int(a["init_ok"]) < int(b["init_ok"]) for a, b in zip(full, bud))
    p = sign_test(win, loss)
    ok = mismatch == 0 and win > loss and p < 0.05
    w.write("\nCPU and GPU picked a different hypothesis on %d CPU-timed scans.\n\n"
            "r = 10 m, full grid against the CPU-sized budget (only full / only budget succeeded): %d / %d, p = %.2g.\n\n"
            "Criterion: %s.\n" % (mismatch, win, loss, p, "met" if ok else "**not met**"))
    with open(os.path.join(ROOT, "docs", "results", "ndt_initial_pose_%s.md" % args.date), "w", encoding="utf-8",
              newline="\n") as f:
        f.write(w.getvalue())
    print(w.getvalue())


if __name__ == "__main__":
    main()

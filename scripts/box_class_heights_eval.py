#!/usr/bin/env python3
"""The learned box class at several sensor heights (gpu_ground_segmentation).

  run    --tag T     runs held-out scenes (seeds 1-20 by default) at each sensor
                     height with the current build (--flags: extra options, e.g.
                     "--height-aware-class") and stores, per tag, the
                     classification of every cluster and every vehicle box
                     observation in tmp/class_heights_<T>_{cls,obs}.csv
  report --base A --new B
                     compares two tags per height: classification (cars, vans,
                     others) and the vehicle boxes completed with the size prior
                     (BEV IoU, centre error), with exact sign tests over the
                     observations and over the seeds; writes <out>.md and <out>.csv
"""

import argparse
import csv
import io
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from box_fitting_heldout import ROOT, find_binary, sign_test  # noqa: E402

VEHICLES = {"0", "1", "2", "4"}


def tmp_path(tag, kind):
    return os.path.join(ROOT, "tmp", "class_heights_%s_%s.csv" % (tag, kind))


def run(args):
    binary = find_binary()
    os.makedirs(os.path.join(ROOT, "tmp"), exist_ok=True)
    cls_rows, obs_rows = [], []
    a, b = (int(x) for x in args.seeds.split("-"))
    for h in args.heights.split(","):
        for seed in range(a, b + 1):
            cls_csv, obs_csv = tmp_path("run", "cls"), tmp_path("run", "obs")
            subprocess.run([binary, "--no-video", "--seed", str(seed), "--sensor-height", h, "--cls-csv", cls_csv,
                            "--obs-csv", obs_csv] + args.flags.split(), cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
            with open(cls_csv, newline="") as f:
                for r in csv.DictReader(f):
                    cls_rows.append({"height": h, "seed": seed, "label": r["label"], "mlp": r["mlp"]})
            with open(obs_csv, newline="") as f:
                for r in csv.DictReader(f):
                    if r["box"] in VEHICLES:
                        obs_rows.append({"height": h, "seed": seed, "scan": r["scan"], "box": r["box"],
                                         "cls_mlp": r["cls_mlp"], "iou": r["iou_prior_mlp"],
                                         "centre": r["centre_prior_mlp"]})
        print("height %s done" % h)
    for kind, rows in (("cls", cls_rows), ("obs", obs_rows)):
        with open(tmp_path(args.tag, kind), "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
    print("wrote", tmp_path(args.tag, "cls"), tmp_path(args.tag, "obs"))


def load(tag, kind):
    with open(tmp_path(tag, kind), newline="") as f:
        return list(csv.DictReader(f))


def class_stats(rows):
    car = [r for r in rows if r["label"] == "0"]
    van = [r for r in rows if r["label"] == "1"]
    oth = [r for r in rows if r["label"] == "2"]
    acc = sum(r["mlp"] == r["label"] for r in rows) / max(1, len(rows))
    return (acc, sum(r["mlp"] == "0" for r in car), len(car), sum(r["mlp"] == "1" for r in van), len(van),
            sum(r["mlp"] != "2" for r in oth), len(oth))


def paired(base, new, metric, lower):
    key = lambda r: (r["seed"], r["scan"], r["box"])
    nb = {key(r): r for r in new}
    w = l = t = 0
    per_seed = {}
    diff = 0.0
    for r in base:
        q = nb[key(r)]
        d = float(q[metric]) - float(r[metric])
        diff += d
        per_seed[r["seed"]] = per_seed.get(r["seed"], 0.0) + d
        if abs(d) < 1e-9:
            t += 1
        elif (d < 0) == lower:
            w += 1
        else:
            l += 1
    sw = sum(1 for d in per_seed.values() if abs(d) > 1e-9 and (d < 0) == lower)
    sl = sum(1 for d in per_seed.values() if abs(d) > 1e-9 and (d < 0) != lower)
    return diff / max(1, len(base)), w, l, t, sign_test(w, l), sw, sl, sign_test(sw, sl)


def report(args):
    cb, cn, ob, on = load(args.base, "cls"), load(args.new, "cls"), load(args.base, "obs"), load(args.new, "obs")
    heights = sorted({r["height"] for r in cb}, key=float)
    w = io.StringIO()
    w.write("# Learned box class at several sensor heights\n\n")
    w.write("Generated by `scripts/box_class_heights_eval.py` from `gpu_ground_segmentation --seed N "
            "--sensor-height H --cls-csv --obs-csv` on held-out scenes (seeds %s). `%s`: the class before, `%s`: "
            "the class after. Boxes: the vehicles' (cars and van) found clusters, completed with the size prior of "
            "the class.\n" % (args.seeds, args.base, args.new))
    w.write("\n## Classification of the clusters\n\n| Height | class | accuracy | cars classed car | vans classed van "
            "| others classed car or van |\n|---:|---|---:|---:|---:|---:|\n")
    for h in heights:
        for tag, rows in ((args.base, cb), (args.new, cn)):
            acc, c_ok, c_n, v_ok, v_n, o_bad, o_n = class_stats([r for r in rows if r["height"] == h])
            w.write("| %s m | %s | %.3f | %d / %d | %d / %d | %d / %d |\n" % (h, tag, acc, c_ok, c_n, v_ok, v_n, o_bad, o_n))
    w.write("\n## Vehicle boxes with the size prior\n\n| Height | observations | IoU %s | IoU %s | centre %s | "
            "centre %s | IoU: observations better / worse / tie (p) | IoU: seeds better / worse (p) |\n"
            "|---:|---:|---:|---:|---:|---:|---:|---:|\n" % (args.base, args.new, args.base, args.new))
    for h in heights:
        b = [r for r in ob if r["height"] == h]
        n = [r for r in on if r["height"] == h]
        mean = lambda rows, k: sum(float(r[k]) for r in rows) / max(1, len(rows))
        diff, wn, ls, t, p, sw, sl, sp = paired(b, n, "iou", False)
        w.write("| %s m | %d | %.3f | %.3f | %.2f m | %.2f m | %d / %d / %d (%.2g) | %d / %d (%.2g) |\n"
                % (h, len(b), mean(b, "iou"), mean(n, "iou"), mean(b, "centre"), mean(n, "centre"), wn, ls, t, p, sw,
                   sl, sp))
    out = os.path.join(ROOT, args.out)
    with open(out + ".md", "w", encoding="utf-8", newline="\n") as f:
        f.write(w.getvalue())
    with open(out + ".csv", "w", newline="") as f:
        wr = csv.writer(f)
        wr.writerow(["tag", "height", "seed", "scan", "box", "cls_mlp", "iou", "centre"])
        for tag, rows in ((args.base, ob), (args.new, on)):
            for r in rows:
                wr.writerow([tag, r["height"], r["seed"], r["scan"], r["box"], r["cls_mlp"], r["iou"], r["centre"]])
    print(w.getvalue())


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--tag", required=True)
    r.add_argument("--heights", default="0.8,1.2,1.8,2.5")
    r.add_argument("--seeds", default="1-20")
    r.add_argument("--flags", default="", help="extra options for gpu_ground_segmentation")
    p = sub.add_parser("report")
    p.add_argument("--base", required=True)
    p.add_argument("--new", required=True)
    p.add_argument("--seeds", default="1-20")
    p.add_argument("--out", default="docs/results/box_class_heights_2026-10-06")
    args = ap.parse_args()
    run(args) if args.cmd == "run" else report(args)


if __name__ == "__main__":
    main()

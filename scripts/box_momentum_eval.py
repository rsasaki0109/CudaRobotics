#!/usr/bin/env python3
"""Residual (momentum) model for the pushing-box turn-path planner: fresh-seed test.

Runs oi_face_rot_turnpath_mppi (smooth rollout model) and
oi_face_rot_turnpath_resid_mppi (smooth model plus the decaying residual of the
last step, oi_dyn = 3) on the two gap cells, smooth and hard-contact true plants,
K=256, 100 fresh seeds per cell (offset 1700 by default, unused by any earlier
step). oi_face_rot_anchor_mppi runs alongside for reference.

Criterion (fixed before the test seeds ran):
  1. hard plant: the residual planner succeeds more often over both cells, and
     the paired sign test (only residual / only turnpath, both cells pooled)
     gives p < 0.05;
  2. no cell on either plant is significantly worse (paired sign test, p < 0.05);
  3. smooth plant: the total does not go down.
"""

import argparse
import csv
import io
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from box_fitting_heldout import ROOT, sign_test  # noqa: E402

BASE, NEW, REF = "oi_face_rot_turnpath_mppi", "oi_face_rot_turnpath_resid_mppi", "oi_face_rot_anchor_mppi"
CELLS = ["box_gap_turn", "box_gap_return"]
PLANTS = ["smooth", "hard"]


def binary():
    for p in ("bin/Release/benchmark_diff_mppi_pushing_box.exe", "bin/benchmark_diff_mppi_pushing_box"):
        if os.path.exists(os.path.join(ROOT, p)):
            return os.path.join(ROOT, p)
    sys.exit("benchmark_diff_mppi_pushing_box not built")


def run(args, plant):
    out = os.path.join(ROOT, "docs", "results", "box_momentum_seed%d_%s_%s.csv" % (args.seed_offset, plant, args.date))
    if not args.reuse or not os.path.exists(out):
        subprocess.run([binary(), "--scenarios", ",".join(CELLS), "--planners", ",".join([REF, BASE, NEW]),
                        "--k-values", "256", "--seed-count", str(args.seed_count), "--seed-offset", str(args.seed_offset),
                        "--true-plant", plant, "--csv", out], cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
    rows = list(csv.DictReader(open(out, newline="")))
    return {(r["scenario"], r["planner"], r["seed"]): int(r["success"]) for r in rows}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed-offset", type=int, default=1700)
    ap.add_argument("--seed-count", type=int, default=100)
    ap.add_argument("--date", default="2026-10-06")
    ap.add_argument("--reuse", action="store_true", help="read the CSVs of an earlier run")
    args = ap.parse_args()

    w = io.StringIO()
    w.write("# Residual momentum model: test on fresh seeds\n\nGenerated by `scripts/box_momentum_eval.py` on seeds "
            "%d-%d (fresh), K=256, %d per cell.\n\n" % (args.seed_offset, args.seed_offset + args.seed_count - 1,
                                                       args.seed_count))
    w.write("| Plant | Cell | `%s` | `%s` | `%s` | paired (only residual / only turnpath) |\n|---|---|---:|---:|---:|---|\n"
            % (REF, BASE, NEW))
    ok = True
    for plant in PLANTS:
        res = run(args, plant)
        tot = {BASE: 0, NEW: 0}
        pw = pl = 0
        for cell in CELLS:
            seeds = sorted({k[2] for k in res if k[0] == cell})
            n = {pn: sum(res[(cell, pn, s)] for s in seeds) for pn in (REF, BASE, NEW)}
            win = sum(res[(cell, NEW, s)] > res[(cell, BASE, s)] for s in seeds)
            loss = sum(res[(cell, NEW, s)] < res[(cell, BASE, s)] for s in seeds)
            p = sign_test(win, loss)
            if loss > win and p < 0.05:
                ok = False
            pw += win; pl += loss
            tot[BASE] += n[BASE]; tot[NEW] += n[NEW]
            w.write("| %s | %s | %d | %d | %d | %d / %d, p = %.2g |\n" % (plant, cell[8:], n[REF], n[BASE], n[NEW], win, loss, p))
        p = sign_test(pw, pl)
        w.write("| %s | both | | %d | %d | %d / %d, p = %.2g |\n" % (plant, tot[BASE], tot[NEW], pw, pl, p))
        if plant == "hard" and not (tot[NEW] > tot[BASE] and pw > pl and p < 0.05):
            ok = False
        if plant == "smooth" and tot[NEW] < tot[BASE]:
            ok = False
    w.write("\nCriterion: %s.\n" % ("met" if ok else "**not met**"))
    with open(os.path.join(ROOT, "docs", "results", "box_momentum_test_%s.md" % args.date), "w", encoding="utf-8",
              newline="\n") as f:
        f.write(w.getvalue())
    print(w.getvalue())


if __name__ == "__main__":
    main()

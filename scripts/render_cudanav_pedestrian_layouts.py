#!/usr/bin/env python3
"""Aggregate crossing-scenario runs over several pedestrian layouts.

The runs directory holds one subdirectory per ``--layout``, each laid out as
:mod:`render_cudanav_dynamic_obstacles` expects::

    runs/crossing/predicted_seed0/ runs/head_on/tracked_scan_seed3/ ...

An optional ``--baseline`` directory with the same layout (for example runs
made before a change) adds its goal and collision counts as a comparison.
Writes ``<prefix>.json``, ``<prefix>.md`` and ``<prefix>.png``.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from render_cudanav_dynamic_obstacles import (  # noqa: E402
    CONDITIONS,
    aggregate,
    load_runs,
    read_trajectory,
)

LAYOUTS = (
    ("crossing", "Crossing (2 pedestrians cross the corridors, wait indefinitely)"),
    ("head_on", "Head-on (2 pedestrians walk the corridors against the robot)"),
    ("overtake", "Overtake (crossing + a faster pedestrian following the robot's route)"),
    ("crowd", "Crowd (5 pedestrians pacing random segments)"),
)


def load_layouts(root: Path) -> dict[str, dict[str, list[dict[str, Any]]]]:
    return {
        layout: load_runs(root / layout)
        for layout, _label in LAYOUTS
        if (root / layout).is_dir()
    }


def summarize(layouts: dict[str, dict[str, list[dict[str, Any]]]]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for layout, groups in layouts.items():
        out[layout] = {}
        for condition, runs in groups.items():
            row = aggregate(runs)
            row["retreat_blocked"] = sum(
                run["summary"].get("retreat_blocked_evaluations") or 0 for run in runs
            )
            row["turnarounds"] = sum(run["summary"].get("pedestrian_turnarounds") or 0 for run in runs)
            row["per_seed"] = [
                {
                    "seed": run["seed"],
                    "goal": bool(run["summary"]["goal_reached"]),
                    "collisions": run["summary"]["dynamic_collisions"]
                    + run["summary"]["wall_collisions"],
                }
                for run in sorted(runs, key=lambda run: run["seed"])
            ]
            out[layout][condition] = row
    return out


def write_markdown(path: Path, report: dict[str, Any]) -> None:
    labels = dict(CONDITIONS)
    baseline = report.get("baseline")
    lines = [
        "# CudaNav pedestrian layouts: dynamic-obstacle MPPI",
        "",
        f"Generated by `scripts/render_cudanav_pedestrian_layouts.py` from {report['total_runs']} runs"
        " of `cudarobotics-cudanav sim --scenario crossing --layout ...`.",
        "Synthetic S-course, one traversal; the tracker is a simulator oracle except in the"
        " scan-tracker condition. See `docs/cudanav_dynamic_obstacles.md`.",
        "",
    ]
    for layout, layout_label in LAYOUTS:
        if layout not in report["layouts"]:
            continue
        header = "| Condition | Goal | Robot-caused collisions | Median time to goal | Retreats (blocked) | Pedestrian turnarounds |"
        rule = "|---|---|---|---|---|---|"
        if baseline and layout in baseline:
            header += " Before: goal | Before: collisions |"
            rule += "---|---|"
        lines += [f"## {layout_label}", "", header, rule]
        for condition, row in report["layouts"][layout].items():
            time_to_goal = (
                "-" if row["median_time_to_goal_s"] is None else f"{row['median_time_to_goal_s']:.1f} s"
            )
            line = (
                f"| {labels.get(condition, condition)} | {row['goal_reached']}/{row['runs']} | "
                f"{row['dynamic_collisions'] + row['wall_collisions']} | {time_to_goal} | "
                f"{row['median_retreats']:.0f} ({row['retreat_blocked']}) | {row['turnarounds']} |"
            )
            if baseline and layout in baseline:
                before = baseline[layout].get(condition)
                line += (
                    f" {before['goal_reached']}/{before['runs']} |"
                    f" {before['dynamic_collisions'] + before['wall_collisions']} |"
                    if before
                    else " - | - |"
                )
            lines.append(line)
        lines.append("")
    lines += [
        "- Goal: runs that reached the goal within 60 s (600 frames).",
        "- Robot-caused collisions: frames where the robot's own motion was stopped by a wall or"
        " would have deepened a pedestrian contact.",
        "- Retreats: median frames per run commanded by the back-out; in brackets, the total"
        " frames whose back-out translation was dropped by the obstacle and lethal-cell checks.",
        "- Pedestrian turnarounds: pedestrians outside `crossing` turn around after waiting 3 s"
        " for the robot.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def write_figure(path: Path, layouts: dict[str, dict[str, list[dict[str, Any]]]], seed: int) -> bool:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import numpy as np
    except ImportError:
        return False
    shown = [layout for layout, _ in LAYOUTS if "predicted" in layouts.get(layout, {})]
    if not shown:
        return False
    figure, axes = plt.subplots(len(shown), 1, figsize=(7.5, 3.6 * len(shown)))
    axes = np.atleast_1d(axes)
    for axis, layout in zip(axes, shown):
        run = next(run for run in layouts[layout]["predicted"] if run["seed"] == seed)
        trajectory = read_trajectory(run["path"])
        axis.plot(trajectory["truth_x"], trajectory["truth_y"], "b-", lw=1.6, label="robot")
        for obstacle in (0, 1):
            axis.plot(
                trajectory[f"obstacle_{obstacle}_x"], trajectory[f"obstacle_{obstacle}_y"],
                ":", color="tab:orange", lw=1.0,
                label="pedestrians 0-1" if obstacle == 0 else None,
            )
        result = "goal" if run["summary"]["goal_reached"] else "timeout"
        axis.set_title(f"{layout}: oracle prediction, seed {seed} ({result})", fontsize=10)
        axis.set_xlim(-1.0, 10.0)
        axis.set_ylim(-2.5, 2.5)
        axis.set_aspect("equal")
        for x0, y0, x1, y1 in (
            (-1.0, -2.5, 10.0, -2.5), (10.0, -2.5, 10.0, 2.5), (10.0, 2.5, -1.0, 2.5),
            (-1.0, 2.5, -1.0, -2.5),
        ):
            axis.plot([x0, x1], [y0, y1], "k-", lw=1.0)
        for min_x, min_y, max_x, max_y in ((3.6, -2.5, 4.3, 0.55), (6.1, -0.55, 6.8, 2.5)):
            axis.add_patch(plt.Rectangle((min_x, min_y), max_x - min_x, max_y - min_y, color="0.6"))
        axis.legend(loc="upper left", fontsize=8)
    figure.tight_layout()
    figure.savefig(path, dpi=100)
    plt.close(figure)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("runs", type=Path, help="directory with one subdirectory per layout")
    parser.add_argument("--baseline", type=Path, help="same layout, runs before a change")
    parser.add_argument("--output-prefix", type=Path, required=True)
    parser.add_argument("--figure-seed", type=int, default=0)
    args = parser.parse_args()

    layouts = load_layouts(args.runs)
    if not layouts:
        raise SystemExit(f"no layout directories under {args.runs}")
    digests = {
        run["source_digest"] for groups in layouts.values() for runs in groups.values() for run in runs
    }
    report: dict[str, Any] = {
        "schema_version": 1,
        "scenario": "cudanav_s_course_crossing",
        "total_runs": sum(len(runs) for groups in layouts.values() for runs in groups.values()),
        "source_digests": sorted(digest for digest in digests if digest),
        "claims": {"synthetic": True, "real_data": False},
        "layouts": summarize(layouts),
    }
    if args.baseline:
        report["baseline"] = summarize(load_layouts(args.baseline))
    prefix = args.output_prefix
    prefix.parent.mkdir(parents=True, exist_ok=True)
    prefix.with_suffix(".json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    write_markdown(prefix.with_suffix(".md"), report)
    if write_figure(prefix.with_suffix(".png"), layouts, args.figure_seed):
        print(f"wrote {prefix.with_suffix('.png')}")
    print(f"wrote {prefix.with_suffix('.json')} and {prefix.with_suffix('.md')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Hybrid tracked boxes on fresh drives (gpu_ground_segmentation --moving).

The motion tracker's boxes beat the static tracker's on moving traffic and
match them on parked cars, but on the moving traffic they lose to the
single-scan box (docs/results/box_motion_2026-10-05.md, seeds 1-20). The hybrid
box takes the single-scan box for the tracks the stand-still test calls moving
and the motion tracker's box for the others. That rule was read off seeds 1-20,
so it is tested here on fresh drives, seeds 21-40, which no earlier step has
run. Seeds 0 and 1-20 are reported for reference only.

Criteria, fixed before the fresh drives ran (mean BEV IoU, boxes with the size prior):
  1. moving vehicles: hybrid >= single scan - 0.01
  2. parked vehicles: hybrid >= motion tracker - 0.01
  3. all vehicles:    hybrid > single scan and hybrid > motion tracker

Writes <out>.csv (fresh-drive vehicle observations) and <out>.md (the report).
"""

import argparse
import csv
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from box_fitting_heldout import ROOT, find_binary  # noqa: E402
from box_motion_eval import compare, run, switches  # noqa: E402

METHODS = [("prior_mlp", "single scan"), ("mtrk_prior", "motion tracker"), ("hybrid", "hybrid")]
LABEL = dict(METHODS)
COMPARISONS = [  # (group, a, b)
    ("moving", "hybrid", "prior_mlp"),
    ("parked", "hybrid", "mtrk_prior"),
    ("all", "hybrid", "prior_mlp"),
    ("all", "hybrid", "mtrk_prior"),
]


def group(rows, g):
    if g == "all":
        return rows
    return [r for r in rows if (float(r["speed"]) > 0) == (g == "moving")]


def mean_iou(rows, key):
    return sum(float(r["iou_" + key]) for r in rows) / max(1, len(rows))


def criteria(rows):
    mv, pk = group(rows, "moving"), group(rows, "parked")
    c1 = mean_iou(mv, "hybrid") >= mean_iou(mv, "prior_mlp") - 0.01
    c2 = mean_iou(pk, "hybrid") >= mean_iou(pk, "mtrk_prior") - 0.01
    c3 = mean_iou(rows, "hybrid") > mean_iou(rows, "prior_mlp") and mean_iou(rows, "hybrid") > mean_iou(rows, "mtrk_prior")
    return c1, c2, c3


def section(w, name, rows):
    w.write("\n## %s\n\n" % name)
    w.write("| Vehicles | observations | single scan | motion tracker | hybrid |\n|---|---:|---:|---:|---:|\n")
    for g in ("moving", "parked", "all"):
        gr = group(rows, g)
        w.write("| %s, BEV IoU | %d | %s |\n" % (g, len(gr), " | ".join("%.3f" % mean_iou(gr, k) for k, _ in METHODS)))
        w.write("| %s, centre error | %d | %s |\n" % (g, len(gr), " | ".join(
            "%.2f m" % (sum(float(r["centre_" + k]) for r in gr) / max(1, len(gr))) for k, _ in METHODS)))
    w.write("\nIdentity switches of the motion tracker: %d.\n" % switches(rows, "mtrack"))
    multi = len({r["seed"] for r in rows}) > 1
    w.write("\n| Vehicles | comparison (BEV IoU) | mean difference | observations better / worse / tie | sign test p |")
    w.write(" seeds better / worse | seed sign test p |\n" if multi else "\n")
    w.write("|---|---|---:|---:|---:|" + ("---:|---:|\n" if multi else "\n"))
    for g, a, b in COMPARISONS:
        diff, wn, ls, t, p, sw, sl, sp = compare(group(rows, g), a, b, "iou", False)
        w.write("| %s | %s vs %s | %+.3f | %d / %d / %d | %.2g |" % (g, LABEL[a], LABEL[b], diff, wn, ls, t, p))
        w.write(" %d / %d | %.2g |\n" % (sw, sl, sp) if multi else "\n")
    c = criteria(rows)
    w.write("\nCriteria: (1) moving, hybrid >= single scan - 0.01: %s; (2) parked, hybrid >= motion tracker - 0.01: "
            "%s; (3) all, hybrid above both: %s.\n" % tuple("met" if x else "**not met**" for x in c))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--fresh", default="21-40", help="fresh seeds a-b")
    ap.add_argument("--reference", default="1-20", help="reference seeds a-b (where the rule came from)")
    ap.add_argument("--out", default="docs/results/box_hybrid_2026-10-06")
    args = ap.parse_args()
    binary = find_binary()
    tmp = os.path.join(ROOT, "tmp")
    os.makedirs(tmp, exist_ok=True)
    tmp_csv = os.path.join(tmp, "box_hybrid_obs.csv")

    def seeds(text):
        a, b = text.split("-")
        return range(int(a), int(b) + 1)

    fresh, ref = [], []
    for sd in seeds(args.fresh):
        fresh += run(binary, sd, tmp_csv)
        print("fresh seed %d done" % sd)
    for sd in seeds(args.reference):
        ref += run(binary, sd, tmp_csv)
    dev = run(binary, 0, tmp_csv)
    w = io.StringIO()
    w.write("# Hybrid tracked boxes: fresh drives\n\n")
    w.write("Generated by `scripts/box_hybrid_eval.py` from `gpu_ground_segmentation --moving --seed N --obs-csv`. "
            "The hybrid box is the single-scan box (with the size prior) for the tracks the stand-still test calls "
            "moving, and the motion tracker's box for the others. The rule came from seeds 1-20; seeds %s are "
            "fresh drives that no earlier step ran. Criteria fixed before the fresh drives ran: (1) moving vehicles, "
            "hybrid >= single scan - 0.01 IoU; (2) parked vehicles, hybrid >= motion tracker - 0.01; (3) all "
            "vehicles, hybrid above both.\n" % args.fresh)
    section(w, "Fresh drives (seeds %s)" % args.fresh, fresh)
    section(w, "Reference: drives the rule came from (seeds %s)" % args.reference, ref)
    section(w, "Reference: dev drive (seed 0)", dev)
    out = os.path.join(ROOT, args.out)
    with open(out + ".csv", "w", newline="") as f:
        wr = csv.DictWriter(f, fieldnames=list(fresh[0].keys()))
        wr.writeheader()
        wr.writerows(fresh)
    with open(out + ".md", "w", encoding="utf-8", newline="\n") as f:
        f.write(w.getvalue())
    print(w.getvalue())


if __name__ == "__main__":
    main()

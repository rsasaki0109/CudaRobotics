#!/usr/bin/env python3
"""GPU relocalization for Monte Carlo localization: test on fresh seeds.

Runs bin/benchmark_mcl_relocalization (all methods, both cells) in the open and
the hard environment on seeds 100-199 by default, unused by any earlier step
(development used seeds 0-29). Writes the CSVs and <out>.md.

Criterion (fixed before the test seeds ran), for `reloc` against `aug`
(augmented MCL, the strongest baseline on the development seeds), in each
environment:
  1. kidnap cell: recovers in more episodes, paired sign test p < 0.05;
  2. global cell: recovers in more episodes, paired sign test p < 0.05;
  3. tracking before the kidnap: the mean fraction of localized steps is not
     lower than aug's by more than 0.03.
"""

import argparse
import csv
import io
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from box_fitting_heldout import ROOT, sign_test  # noqa: E402

METHODS = ["mcl", "aug", "er", "reloc", "reloc_lr"]
ENVS = ["open", "hard"]


def binary():
    for p in ("bin/Release/benchmark_mcl_relocalization.exe", "bin/benchmark_mcl_relocalization"):
        if os.path.exists(os.path.join(ROOT, p)):
            return os.path.join(ROOT, p)
    sys.exit("benchmark_mcl_relocalization not built")


def run(args, env):
    out = os.path.join(ROOT, "docs", "results", "mcl_relocalization_seed%d_%s_%s.csv" % (args.seed_offset, env, args.date))
    if not args.reuse or not os.path.exists(out):
        subprocess.run([binary(), "--env", env, "--seed-offset", str(args.seed_offset), "--seed-count",
                        str(args.seed_count), "--csv", out], cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
    return list(csv.DictReader(open(out, newline="")))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed-offset", type=int, default=100)
    ap.add_argument("--seed-count", type=int, default=100)
    ap.add_argument("--date", default="2026-10-06")
    ap.add_argument("--reuse", action="store_true", help="read the CSVs of an earlier run")
    args = ap.parse_args()

    w = io.StringIO()
    w.write("# GPU relocalization for MCL: test on fresh seeds\n\nGenerated by `scripts/mcl_relocalization_eval.py` on "
            "seeds %d-%d (fresh; development used 0-29).\n\n" % (args.seed_offset, args.seed_offset + args.seed_count - 1))
    ok = True
    for env in ENVS:
        rows = run(args, env)
        by = {(r["cell"], r["method"], r["seed"]): r for r in rows}
        seeds = sorted({r["seed"] for r in rows}, key=int)
        n = len(seeds)
        w.write("## Environment `%s`\n\n| Method | kidnap: recovered | steps to recover (median) | localized after | "
                "final | before the kidnap: localized | global: recovered | final | grid search ms |\n"
                "|---|---:|---:|---:|---:|---:|---:|---:|---:|\n" % env)
        stat = {}
        for m in METHODS:
            k = [by[("kidnap", m, s)] for s in seeds]
            g = [by[("global", m, s)] for s in seeds]
            rec = sum(int(r["recovered"]) for r in k)
            st = sorted(int(r["recover_steps"]) for r in k if r["recovered"] == "1")
            med = st[len(st) // 2] if st else -1
            lb = sum(float(r["localized_before"]) for r in k) / n
            stat[m] = lb
            ms = [float(r["reloc_ms"]) for r in k + g if float(r["reloc_ms"]) > 0]
            w.write("| `%s` | %d/%d | %s | %.2f | %d | %.3f | %d/%d | %d | %s |\n" % (
                m, rec, n, med if med >= 0 else "-", sum(float(r["localized_frac"]) for r in k) / n,
                sum(int(r["final_ok"]) for r in k), lb, sum(int(r["recovered"]) for r in g), n,
                sum(int(r["final_ok"]) for r in g), "%.2f" % (sum(ms) / len(ms)) if ms else "-"))
        w.write("\n`reloc` against `aug`, paired by seed (only reloc / only aug recovered):\n\n")
        for cell in ("kidnap", "global"):
            win = sum(by[(cell, "reloc", s)]["recovered"] > by[(cell, "aug", s)]["recovered"] for s in seeds)
            loss = sum(by[(cell, "reloc", s)]["recovered"] < by[(cell, "aug", s)]["recovered"] for s in seeds)
            p = sign_test(win, loss)
            w.write("- %s: %d / %d, p = %.2g\n" % (cell, win, loss, p))
            if not (win > loss and p < 0.05):
                ok = False
        if stat["reloc"] < stat["aug"] - 0.03:
            ok = False
        w.write("- before the kidnap, localized: reloc %.3f, aug %.3f\n\n" % (stat["reloc"], stat["aug"]))
    w.write("Criterion: %s.\n" % ("met" if ok else "**not met**"))
    with open(os.path.join(ROOT, "docs", "results", "mcl_relocalization_test_%s.md" % args.date), "w",
              encoding="utf-8", newline="\n") as f:
        f.write(w.getvalue())
    print(w.getvalue())


if __name__ == "__main__":
    main()

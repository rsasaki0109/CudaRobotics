#!/usr/bin/env python3
"""A box class on the drives (gpu_ground_segmentation --sequence and --moving).

The per-cluster report (box_class_heights_eval.py) can miss what a class does
to the trackers on a drive: the drives show lane traffic end-on, which the
random scenes do not. This script runs, for a class, the drives of the given
seeds from 1.8 m and compares two classes on the vehicles' boxes completed with
the size prior:

  tracked     the static tracker on --sequence drives (cars and the van)
  motion      the motion tracker on --moving drives (all vehicles)
  single      the single-scan box on --moving drives (all vehicles)
  hybrid      the hybrid box on --moving drives (all vehicles)

  run    --tag T [--flags "..."]   stores tmp/class_drives_<T>.csv
  report --base A --new B          compares, with exact sign tests per
                                   observation and per seed; writes <out>.md

Criterion for a new class to replace the default (fixed before the fresh seeds
41-60 ran): on every metric the mean IoU drops by no more than 0.005, and the
new class is not worse in significantly more seeds (two-sided sign test,
p < 0.05).
"""

import argparse
import csv
import io
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from box_fitting_heldout import ROOT, find_binary, sign_test  # noqa: E402

METRICS = [("tracked", "sequence", "iou_trk_prior", {"0", "1", "2", "4"}),
           ("motion", "moving", "iou_mtrk_prior", {"0", "1", "2", "4", "7", "8"}),
           ("single", "moving", "iou_prior_mlp", {"0", "1", "2", "4", "7", "8"}),
           ("hybrid", "moving", "iou_hybrid", {"0", "1", "2", "4", "7", "8"})]


def tmp_path(tag):
    return os.path.join(ROOT, "tmp", "class_drives_%s.csv" % tag)


def run(args):
    binary = find_binary()
    obs = os.path.join(ROOT, "tmp", "class_drives_run.csv")
    rows = []
    a, b = (int(x) for x in args.seeds.split("-"))
    for seed in range(a, b + 1):
        for mode in ("sequence", "moving"):
            subprocess.run([binary, "--no-video", "--" + mode, "--seed", str(seed), "--obs-csv", obs]
                           + args.flags.split(), cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
            with open(obs, newline="") as f:
                for r in csv.DictReader(f):
                    for name, m, col, boxes in METRICS:
                        if m == mode and r["box"] in boxes:
                            rows.append({"metric": name, "seed": seed, "scan": r["scan"], "box": r["box"],
                                         "iou": r[col]})
        print("seed %d done" % seed)
    with open(tmp_path(args.tag), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def report(args):
    def load(tag):
        with open(tmp_path(tag), newline="") as f:
            return list(csv.DictReader(f))

    base, new = load(args.base), load(args.new)
    w = io.StringIO()
    w.write("# Box class on the drives\n\nGenerated by `scripts/box_class_drives_eval.py`: drives of seeds %s from "
            "1.8 m; `%s` vs `%s`. Boxes: the vehicles', completed with the size prior. Criterion (fixed before the "
            "run): on every metric the mean IoU drops by at most 0.005 and the new class is not worse in "
            "significantly more seeds (p < 0.05).\n\n" % (args.seeds, args.base, args.new))
    w.write("| Boxes | observations | IoU %s | IoU %s | observations better / worse / tie (p) | seeds better / worse (p) "
            "| criterion |\n|---|---:|---:|---:|---:|---:|---|\n" % (args.base, args.new))
    ok_all = True
    for name, _, _, _ in METRICS:
        key = lambda r: (r["seed"], r["scan"], r["box"])
        b = {key(r): float(r["iou"]) for r in base if r["metric"] == name}
        n = {key(r): float(r["iou"]) for r in new if r["metric"] == name}
        ks = [k for k in b if k in n]
        wn = sum(n[k] - b[k] > 1e-9 for k in ks)
        ls = sum(n[k] - b[k] < -1e-9 for k in ks)
        per_seed = {}
        for k in ks:
            per_seed[k[0]] = per_seed.get(k[0], 0.0) + n[k] - b[k]
        sw = sum(d > 1e-9 for d in per_seed.values())
        sl = sum(d < -1e-9 for d in per_seed.values())
        mb, mn = sum(b[k] for k in ks) / len(ks), sum(n[k] for k in ks) / len(ks)
        sp = sign_test(sw, sl)
        ok = mn - mb >= -0.005 and not (sl > sw and sp < 0.05)
        ok_all = ok_all and ok
        w.write("| %s | %d | %.3f | %.3f | %d / %d / %d (%.2g) | %d / %d (%.2g) | %s |\n"
                % (name, len(ks), mb, mn, wn, ls, len(ks) - wn - ls, sign_test(wn, ls), sw, sl, sp,
                   "met" if ok else "**not met**"))
    w.write("\nCriterion %s on every metric.\n" % ("met" if ok_all else "**not met**"))
    with open(os.path.join(ROOT, args.out) + ".md", "w", encoding="utf-8", newline="\n") as f:
        f.write(w.getvalue())
    print(w.getvalue())


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--tag", required=True)
    r.add_argument("--seeds", default="41-60")
    r.add_argument("--flags", default="")
    p = sub.add_parser("report")
    p.add_argument("--base", required=True)
    p.add_argument("--new", required=True)
    p.add_argument("--seeds", default="41-60")
    p.add_argument("--out", default="docs/results/box_class_drives_2026-10-06")
    args = ap.parse_args()
    run(args) if args.cmd == "run" else report(args)


if __name__ == "__main__":
    main()

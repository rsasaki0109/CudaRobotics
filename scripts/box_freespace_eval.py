#!/usr/bin/env python3
"""Free-space box refinement (gpu_ground_segmentation): tuning and test.

The refinement scores candidate boxes around each completed box by the free
space the scan's rays crossed inside them, the cluster's points left outside,
and the change of size (weights w_free, w_out, w_size; --fs-weights). Compared
with the completed box it starts from, on the vehicles' boxes (cars and van).

  tune   grid over w_out and w_size (w_free = 1) on the dev scene (seed 0) and
         training seeds 101-110 only; prints the mean IoU of each setting
  test   one setting on fresh seeds (61-80 by default, unused by any earlier
         step); writes <out>.md

Criterion (fixed before the test seeds ran): the mean BEV IoU rises, the
refinement is better in significantly more seeds than worse (two-sided sign
test, p < 0.05), and the mean centre error does not rise.
"""

import argparse
import csv
import io
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from box_fitting_heldout import ROOT, find_binary, sign_test  # noqa: E402

VEH = {"0", "1", "2", "4"}


def collect(binary, seeds, weights):
    obs = os.path.join(ROOT, "tmp", "fs_obs.csv")
    rows = []
    for seed in seeds:
        subprocess.run([binary, "--no-video", "--seed", str(seed), "--fs-weights", weights, "--obs-csv", obs],
                       cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
        with open(obs, newline="") as f:
            rows += [r for r in csv.DictReader(f) if r["box"] in VEH]
    return rows


def mean(rows, col):
    return sum(float(r[col]) for r in rows) / max(1, len(rows))


def tune(args):
    binary = find_binary()
    seeds = [0] + list(range(101, 111))
    print("dev seed 0 and training seeds 101-110")
    for w_out in (3, 10, 30):
        for w_size in (10, 50, 200):
            weights = "1,%g,%g" % (w_out, w_size)
            rows = collect(binary, seeds, weights)
            print("w_free 1 w_out %4g w_size %4g: IoU %.4f -> %.4f, centre %.3f -> %.3f m (%d boxes)"
                  % (w_out, w_size, mean(rows, "iou_prior_mlp"), mean(rows, "iou_fs"), mean(rows, "centre_prior_mlp"),
                     mean(rows, "centre_fs"), len(rows)))


def test(args):
    binary = find_binary()
    a, b = (int(x) for x in args.seeds.split("-"))
    rows = collect(binary, range(a, b + 1), args.weights)
    per_seed = {}
    wn = ls = 0
    for r in rows:
        d = float(r["iou_fs"]) - float(r["iou_prior_mlp"])
        per_seed[r["seed"]] = per_seed.get(r["seed"], 0.0) + d
        wn += d > 1e-9; ls += d < -1e-9
    sw = sum(d > 1e-9 for d in per_seed.values()); sl = sum(d < -1e-9 for d in per_seed.values())
    i0, i1 = mean(rows, "iou_prior_mlp"), mean(rows, "iou_fs")
    c0, c1 = mean(rows, "centre_prior_mlp"), mean(rows, "centre_fs")
    p = sign_test(sw, sl)
    ok = i1 > i0 and sw > sl and p < 0.05 and c1 <= c0
    w = io.StringIO()
    w.write("# Free-space box refinement: test on fresh seeds\n\nGenerated by `scripts/box_freespace_eval.py test` "
            "(weights w_free, w_out, w_size = %s, chosen on the dev scene and training seeds 101-110). Seeds %s are "
            "fresh. Vehicles' boxes (cars and the van), from 1.8 m.\n\n" % (args.weights, args.seeds))
    w.write("| Box | observations | BEV IoU | IoU >= 0.5 | centre error |\n|---|---:|---:|---:|---:|\n")
    for col, name in (("prior_mlp", "L-shape + size prior"), ("fs", "+ free-space refinement")):
        w.write("| %s | %d | %.3f | %d | %.2f m |\n" % (name, len(rows), mean(rows, "iou_" + col),
                                                       sum(float(r["iou_" + col]) >= 0.5 for r in rows),
                                                       mean(rows, "centre_" + col)))
    w.write("\nPer observation: better / worse / tie %d / %d / %d (sign test p %.2g). Per seed: better / worse %d / %d "
            "(p %.2g).\n\nCriterion (IoU up, better in significantly more seeds, centre error not up): %s.\n"
            % (wn, ls, len(rows) - wn - ls, sign_test(wn, ls), sw, sl, p, "met" if ok else "**not met**"))
    with open(os.path.join(ROOT, args.out) + ".md", "w", encoding="utf-8", newline="\n") as f:
        f.write(w.getvalue())
    print(w.getvalue())


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("tune")
    t = sub.add_parser("test")
    t.add_argument("--weights", required=True, help="w_free,w_out,w_size")
    t.add_argument("--seeds", default="61-80")
    t.add_argument("--out", default="docs/results/box_freespace_2026-10-06")
    args = ap.parse_args()
    tune(args) if args.cmd == "tune" else test(args)


if __name__ == "__main__":
    main()
